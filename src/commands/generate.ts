import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { Command } from "commander";
import * as toml from "smol-toml";
import { withErrorHandling } from "../core/cliError.ts";
import { loadConfig } from "../core/config/config.ts";
import { log } from "../core/logger.ts";
import { generateCollection } from "../core/openapi/generate.ts";
import { loadOpenApiSpec } from "../core/openapi/loader.ts";

export interface GenerateOptions {
  from?: string;
  out?: string;
  security?: string;
  allowLocal?: boolean;
  insecure?: boolean;
}

export interface PerformGenerateOptions {
  security?: string;
  allowLocal?: boolean;
  insecure?: boolean;
  /** Called with progress lines as loading/generating happens — the CLI
   *  passes log.dim to stream them, the MCP tool omits this entirely (it
   *  must never write to stdout, that's the stdio transport's protocol
   *  channel) and just uses the returned result instead. */
  onProgress?: (message: string) => void;
}

export interface PerformGenerateResult {
  specTitle: string;
  pathCount: number;
  out: string;
  requestCount: number;
  reviewNotes: string[];
  workflowPath?: string;
}

// The actual work, with progress reported via a callback instead of direct
// console output — reused by the CLI command below and by the MCP
// generate_collection tool.
export async function performGenerate(
  from: string,
  out: string,
  options: PerformGenerateOptions = {}
): Promise<PerformGenerateResult> {
  options.onProgress?.(
    `Loading OpenAPI spec from ${from}${options.allowLocal ? " (--allow-local)" : ""}${options.insecure ? " (--insecure)" : ""}...`
  );
  const spec = await loadOpenApiSpec(from, {
    allowLocal: options.allowLocal,
    insecure: options.insecure,
  });
  const pathCount = Object.keys(spec.paths ?? {}).length;
  const specTitle = spec.info?.title ?? "untitled spec";
  options.onProgress?.(`Loaded "${specTitle}" — ${pathCount} path(s)`);

  options.onProgress?.(
    `Generating collection${options.security ? ` (security: ${options.security})` : ""}...`
  );
  const { meta, requests, reviewNotes, workflow } = generateCollection(spec, {
    preferredSecurityScheme: options.security,
  });

  const body = toml.stringify({ meta, request: requests });
  const header =
    reviewNotes.length > 0
      ? `# Generated by \`shimwire generate\` — review before relying on this in CI:\n${reviewNotes
          .map((note) => `#   - ${note}`)
          .join("\n")}\n\n`
      : `# Generated by \`shimwire generate\`\n\n`;

  options.onProgress?.(`Writing ${out}...`);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, header + body);

  let workflowPath: string | undefined;
  if (workflow) {
    workflowPath = join(process.cwd(), ".shimwire", "workflows", `${workflow.name}.toml`);
    const workflowBody = toml.stringify({ request: workflow.requests });
    await mkdir(dirname(workflowPath), { recursive: true });
    await writeFile(
      workflowPath,
      `# Generated by \`shimwire generate\` — review credentials before relying on this in CI\n\n${workflowBody}`
    );
  }

  return { specTitle, pathCount, out, requestCount: requests.length, reviewNotes, workflowPath };
}

export async function runGenerate(options: GenerateOptions): Promise<void> {
  const config = (await loadConfig()).generate ?? {};

  const from = options.from ?? config.from;
  const out = options.out ?? config.out;
  if (!from) {
    throw new Error(
      'Missing "from": pass --from <spec> or set generate.from in .shimwire/config.toml'
    );
  }
  if (!out) {
    throw new Error(
      'Missing "out": pass --out <path> or set generate.out in .shimwire/config.toml'
    );
  }
  const security = options.security ?? config.security;
  const allowLocal = options.allowLocal ?? config.allow_local ?? false;
  const insecure = options.insecure ?? config.insecure ?? false;

  const usedConfigKeys = [
    options.from == null && config.from != null && "from",
    options.out == null && config.out != null && "out",
    options.security == null && config.security != null && "security",
    options.allowLocal == null && config.allow_local != null && "allow_local",
    options.insecure == null && config.insecure != null && "insecure",
  ].filter((key): key is string => Boolean(key));
  if (usedConfigKeys.length > 0) {
    log.dim(`Using .shimwire/config.toml defaults for: ${usedConfigKeys.join(", ")}`);
  }

  const result = await performGenerate(from, out, {
    security,
    allowLocal,
    insecure,
    onProgress: (message) => log.dim(message),
  });

  log.success(`Wrote ${result.requestCount} request(s) to ${out}`);

  if (result.workflowPath) {
    log.success(`Wrote reusable workflow to ${result.workflowPath}`);
  }

  if (result.reviewNotes.length > 0) {
    log.warn(`${result.reviewNotes.length} item(s) flagged for manual review — see file header.`);
  }
}

export function registerGenerateCommand(program: Command): void {
  program
    .command("generate")
    .description(
      "Auto-scaffold a starter collection from an OpenAPI spec (flags override .shimwire/config.toml [generate] defaults)"
    )
    .option("-f, --from <spec>", "path to an OpenAPI 3.x spec (yaml or json, or a URL)")
    .option("-o, --out <path>", "output path for the generated collection .toml")
    .option(
      "-s, --security <schemeName>",
      "when an operation accepts multiple auth schemes, prefer this securitySchemes name"
    )
    .option(
      "-l, --allow-local",
      "allow fetching --from specs from localhost/private-network URLs (disables swagger-parser's SSRF guard)"
    )
    .option(
      "-k, --insecure",
      "skip TLS certificate verification while fetching --from (self-signed/local dev certs)"
    )
    .action(withErrorHandling(runGenerate));
}
